#[test]
fn finite_factories_integer_limits_and_signed_zero_are_explicit() {
    assert!(Extended::from_f64(f64::INFINITY).is_none());
    assert!(Extended::from_f64(f64::NAN).is_none());
    for value in [i64::MIN, -1, 0, 1, i64::MAX] {
        assert_eq!(Extended::from_i64(value).round_i64(), Some(value));
    }
    let p = Extended::from_f64(0.0).unwrap();
    let n = Extended::from_f64(-0.0).unwrap();
    assert_eq!(p.add(n).unwrap().to_f64().to_bits(), 0.0_f64.to_bits());
    assert_eq!(n.add(n).unwrap().to_f64().to_bits(), (-0.0_f64).to_bits());
    assert_eq!(p.div(n), Err(Fault::DivisionByZero));
    let tiny = Extended::from_f64(-1e-308)
        .unwrap()
        .mul(Extended::from_f64(1e-20).unwrap())
        .unwrap();
    assert_eq!(tiny.floor().to_f64(), -1.0);
    assert!(!tiny.is_zero());
    assert!(tiny.is_negative());
    assert!(!tiny.abs().is_negative());
}
