//! Column width conversions, using the Normal font's digit width in pixels.

/// The Normal-font gutter: a quarter of a digit on each side, rounded up,
/// and the grid line. Its size changes with the font's digit width.
pub fn padding_pixels(digit: f64) -> f64 { 2.0 * (digit / 4.0).ceil() + 1.0 }

/// An untouched eight-character column occupies a multiple of eight pixels.
pub fn default_column_pixels(digit: f64) -> f64 {
    ((8.0 * digit + padding_pixels(digit)) / 8.0).ceil() * 8.0
}

/// Turn character units into whole pixels, including the cell gutter.
pub fn characters_to_pixels(characters: f64, digit: f64) -> f64 {
    if characters < 1.0 {
        (characters * (digit + padding_pixels(digit))).round()
    } else {
        (characters * digit + padding_pixels(digit)).round()
    }
}

/// Decode the gutter-inclusive width stored in a worksheet's column record.
pub fn stored_width_to_pixels(stored: f64, digit: f64) -> f64 {
    (((256.0 * stored + (128.0 / digit).trunc()) / 256.0) * digit).trunc()
}

/// Below one character the gutter shrinks together with the text area.
pub fn pixels_to_characters(pixels: f64, digit: f64) -> f64 {
    if pixels < digit + padding_pixels(digit) {
        pixels / (digit + padding_pixels(digit))
    } else {
        (pixels - padding_pixels(digit)) / digit
    }
}

