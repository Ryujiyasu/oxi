/// The measured default row height for a font, in 96-dpi pixels.
pub(crate) fn font_default_row_px(face: &str, size: f32) -> Option<u16> {
    let size_q = (size * 4.0).round() as u16;
    FONT_DEFAULT_ROW_PX
        .iter()
        .find(|(f, s, _)| *f == face && *s == size_q)
        .map(|(_, _, px)| *px)
}
